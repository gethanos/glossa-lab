export const DEFAULT_DIALECT = 'glossa';

export function getDialect(id) {
  return DIALECTS[id] || DIALECTS[DEFAULT_DIALECT];
}

/**
 * Αναγνωρίζει τη γλώσσα από την πρώτη λέξη του κώδικα (αγνοώντας κενές γραμμές και σχόλια).
 * @returns {'glossa' | 'pseudo' | null}
 */
export function detectDialect(source) {
  for (const line of source.split('\n')) {
    const text = line.trim();
    if (!text || text.startsWith('!')) continue;
    const word = normalize((text.match(/^[A-Za-z\u0370-\u03FF\u1F00-\u1FFF_]+/) || [''])[0]);
    if (word === DIALECTS.glossa.unitKeyword) return 'glossa';
    if (word === DIALECTS.pseudo.unitKeyword) return 'pseudo';
    return null;
  }
  return null;
}
