export const PHASE_LABEL = Object.freeze({
  lexical: 'Συντακτικό λάθος',
  syntax: 'Συντακτικό λάθος',
  semantic: 'Συντακτικό λάθος',
  runtime: 'Λάθος αντικανονικού τερματισμού',
});
export const WARNING_LABEL = 'Προειδοποίηση: πιθανό λογικό λάθος';

export class GlossaError extends Error {
  /**
   * @param {string} code κωδικός από τον CATALOG
   * @param {object} where { line, col, length }
   * @param {object} params δεδομένα για τα κείμενα
   * @param {'error'|'warning'} severity
   */
  constructor(code, where = {}, params = {}, severity = 'error') {
    const entry = CATALOG[code];
    super(entry ? entry.title(params) : code);
    this.code = code;
    this.phase = entry ? entry.phase : Phase.RUNTIME;
    this.line = where.line ?? 0;
    this.col = where.col ?? 0;
    this.length = where.length ?? 1;
    this.params = params;
    this.severity = severity;
  }
}

export function warning(code, where, params) {
  return new GlossaError(code, where, params, 'warning');
}

/**
 * Προσαρμόζει το σφάλμα στη γλώσσα του κώδικα (ονόματα εντολών, παραδείγματα).
 * @param {GlossaError} err
 * @param {'glossa'|'pseudo'} dialect
 */
export function localize(err, dialect) {
  err.params = { ...err.params, dialect };
  const entry = CATALOG[err.code];
  if (entry) err.message = entry.title(err.params);
  return err;
}

/**
 * Επιστρέφει όλα τα κείμενα ενός σφάλματος για εμφάνιση.
 * @param {GlossaError} err
 * @param {'glossa'|'pseudo'} dialect η γλώσσα, για παραδείγματα και ονόματα εντολών
 */
export function describe(err, dialect = (err.params && err.params.dialect) || 'glossa') {
  const entry = CATALOG[err.code];
  if (!entry) {
    return { title: err.message, explain: '', fix: '', example: '', phaseLabel: PHASE_LABEL.runtime };
  }
  const p = { ...(err.params || {}), dialect };
  return {
    title: entry.title(p),
    explain: entry.explain(p),
    fix: entry.fix(p),
    example: entry.example ? entry.example(p) : '',
    phaseLabel: err.severity === 'warning' ? WARNING_LABEL : PHASE_LABEL[entry.phase],
  };
}

